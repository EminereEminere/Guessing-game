#!/usr/bin/env python3
"""Convert the question text files in ../questions-src/*.txt into ../questions.js.

Each .txt file is one category, written in the same format the questions were
pasted in:

    Category: Geography / Geografia / 🌍

    1. (Easy) What is the capital of Australia?
    Qual é a capital da Austrália?

    1. Sydney / Sydney
    2. Melbourne / Melbourne
    3. Canberra / Canberra
    4. Perth / Perth

    ...

    Answer Key / Gabarito

    1. 3 – Canberra

Run:  python3 quem-bebe/tools/build_questions.py
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "questions-src"
OUT = ROOT / "questions.js"

LEVELS = {"easy": "easy", "medium": "medium", "difficult": "hard", "hard": "hard"}
NUM = re.compile(r"^(\d+)\.\s*(.*)$")
LEVEL = re.compile(r"^\((\w+)\)\s*(.*)$")
KEY = re.compile(r"^(\d+)\.\s*([1-4])\s*[–\-—:]\s*(.*)$")


def split_pair(text):
    if " / " in text:
        en, pt = text.split(" / ", 1)
        return [en.strip(), pt.strip()]
    return [text.strip(), text.strip()]


def parse(path):
    lines = [l.strip() for l in path.read_text(encoding="utf-8").splitlines()]
    lines = [l for l in lines if l]
    head = lines.pop(0)
    if not head.lower().startswith("category:"):
        sys.exit(f"{path.name}: first line must be 'Category: English / Português / emoji'")
    parts = [p.strip() for p in head.split(":", 1)[1].split(" / ")]
    cat = {"id": path.stem, "en": parts[0], "pt": parts[1] if len(parts) > 1 else parts[0],
           "icon": parts[2] if len(parts) > 2 else "❓", "questions": []}

    try:
        key_at = next(i for i, l in enumerate(lines) if l.lower().startswith("answer key"))
    except StopIteration:
        sys.exit(f"{path.name}: missing 'Answer Key / Gabarito' section")
    body, keys = lines[:key_at], lines[key_at + 1:]

    questions = {}
    i = 0
    while i < len(body):
        m = NUM.match(body[i])
        lm = LEVEL.match(m.group(2)) if m else None
        if not lm:
            sys.exit(f"{path.name}: expected '<n>. (Easy|Medium|Difficult) question', got: {body[i]}")
        n = int(m.group(1))
        level = LEVELS.get(lm.group(1).lower())
        if not level:
            sys.exit(f"{path.name} q{n}: unknown difficulty '{lm.group(1)}'")
        q_en, q_pt = lm.group(2), body[i + 1]
        opts = []
        for j in range(4):
            om = NUM.match(body[i + 2 + j])
            if not om or int(om.group(1)) != j + 1:
                sys.exit(f"{path.name} q{n}: expected option {j + 1}, got: {body[i + 2 + j]}")
            opts.append(split_pair(om.group(2)))
        questions[n] = {"level": level, "q": [q_en, q_pt], "options": opts}
        i += 6

    for line in keys:
        km = KEY.match(line)
        if not km:
            sys.exit(f"{path.name}: bad answer key line: {line}")
        n, ans, label = int(km.group(1)), int(km.group(2)), km.group(3).strip()
        if n not in questions:
            sys.exit(f"{path.name}: answer key for unknown question {n}")
        opt_en = questions[n]["options"][ans - 1][0]
        # The key label may be a shortened version of the option; warn only if they don't overlap.
        a, b = label.lower().rstrip("."), opt_en.lower()
        if label and a != b and a not in b and b not in a:
            words = set(re.findall(r"\w+", a)) - {"the", "a", "of", "and", "to"}
            if not words or not words <= set(re.findall(r"\w+", b)):
                print(f"  ⚠ {path.name} q{n}: key says '{label}' but option {ans} is '{opt_en}'")
        questions[n]["answer"] = ans

    for n, q in sorted(questions.items()):
        if "answer" not in q:
            sys.exit(f"{path.name} q{n}: no answer in the answer key")
        cat["questions"].append(q)
    return cat


def main():
    files = sorted(SRC.glob("*.txt"))
    cats = [parse(f) for f in files]
    js = ("// GENERATED by tools/build_questions.py from questions-src/*.txt — edit those, then re-run.\n"
          "// answer = number of the correct option (1-4).\n"
          "window.QUIZ_CATEGORIES = " + json.dumps(cats, ensure_ascii=False, indent=1) + ";\n")
    OUT.write_text(js, encoding="utf-8")
    for c in cats:
        print(f"{c['icon']} {c['en']}: {len(c['questions'])} questions")


if __name__ == "__main__":
    main()
